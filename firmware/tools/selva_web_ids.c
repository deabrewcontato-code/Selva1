/* Prints, as a JS module, what the Selva1 web panel (web/selva) needs from the firmware's headers: the ids of the track
 * and global parameters it moves, the tables it shows values with. Built and run by tools/build_selva_web.py. */
#include <stdio.h>
#include <stdint.h>
#include "felucca_tables.h"
#include "../firmware/src/core.h"
#define ID(x) printf("  %s: %d,\n", #x, (int)(x))
static void tab_u32(const char *name, const uint32_t *t, int n)
{
    printf("export const %s = [", name);
    for (int i = 0; i < n; i++) printf("%s%u", i ? "," : "", (unsigned)t[i]);
    printf("];\n");
}
static void tab_u16(const char *name, const uint16_t *t, int n)
{
    printf("export const %s = [", name);
    for (int i = 0; i < n; i++) printf("%s%u", i ? "," : "", (unsigned)t[i]);
    printf("];\n");
}
int main(void)
{
    printf("// generated by tools/selva_web_ids.c from the firmware's headers: do not edit\nexport const P = {\n");
    ID(P_LEVEL); ID(P_ATK); ID(P_DEC); ID(P_SUS); ID(P_REL); ID(P_ED_FLT); ID(P_ED_PIT); ID(P_ED_SHP); ID(P_ED_FX);
    ID(P_LRATE); ID(P_LWAVE); ID(P_LPHASE); ID(P_LFADE); ID(P_LD_PIT); ID(P_LD_FLT); ID(P_LD_SHP); ID(P_LD_AMP);
    ID(P_AMODE); ID(P_ARATE); ID(P_AOCT); ID(P_AGATE); ID(P_TRANS); ID(P_DIST); ID(P_CHOR); ID(P_DLY); ID(P_REV);
    ID(P_VOICE); ID(P_GLIDE); ID(P_PAN); ID(P_GLMODE); ID(P_DETUNE); ID(P_LSYNC); ID(P_LTRIG); ID(P_LPOL);
    ID(P_E0); ID(P_COUNT);
    printf("};\nexport const G = {\n");
    ID(G_BPM); ID(G_DTIME); ID(G_DFDBK); ID(G_DCOLOR); ID(G_DMIX); ID(G_RSIZE); ID(G_RDAMP); ID(G_CRATE); ID(G_CDEPTH);
    ID(G_COUNT);
    printf("};\n");
    tab_u16("CUTOFF_HZ", CUTOFF_HZ, 128);
    tab_u32("TIME_MS_X10", TIME_MS_X10, 128);
    tab_u32("LFO_HZ_X100", LFO_HZ_X100, 128);
    printf("export const FS = %d, CTL = %d;\n", FS, CTL);
    return 0;
}
